export const messages: Record<Lang, Dict> = { ru, uz }

export function normalizeLang(value: string | undefined | null): Lang {
  return value === 'uz' ? 'uz' : 'ru'
}

/** Название категории на текущем языке (в БД есть name_ru / name_uz). */
export function categoryName(
  c: { name_ru: string; name_uz?: string | null },
  lang: Lang,
): string {
  return lang === 'uz' && c.name_uz ? c.name_uz : c.name_ru
}
