export const messages: Record<Lang, Dict> = { ru, uz, en }

export function normalizeLang(value: string | undefined | null): Lang {
  return value === 'en' || value === 'uz' ? value : 'ru'
}

/** Название категории на текущем языке (в БД есть name_ru / name_uz). */
export function categoryName(
  c: { name_ru: string; name_uz?: string | null },
  lang: Lang,
): string {
  if (lang === 'en') {
    const labels: Record<string, string> = {
      'Одежда и обувь': 'Clothing and shoes',
      'Косметика и бьюти': 'Beauty and skincare',
      'Нижнее бельё': 'Lingerie',
      'Салоны и массаж': 'Salons and massage',
      'Детские товары': 'Kids',
      'Товары для дома': 'Home',
      'Здоровье и гигиена': 'Health and wellness',
      'Продукты': 'Groceries',
    }
    return labels[c.name_ru] ?? c.name_ru
  }
  return lang === 'uz' && c.name_uz ? c.name_uz : c.name_ru
}
